#!/usr/bin/env python3
"""Generate synthetic AGD memory files for benchmarking.

Deterministic with --seed. Sizes: number of x-* blocks (the meta/header
overhead is constant). Output mirrors the structure of a real memory.agd
produced by the agd-memory plugin.
"""
from __future__ import annotations

import argparse
import random
from pathlib import Path

KINDS = [
    ("x-user", 0.10),
    ("x-feedback", 0.40),
    ("x-project", 0.35),
    ("x-reference", 0.15),
]

TOPICS = {
    "x-user": ["role", "blog", "stile", "domain", "tools", "languages", "schedule"],
    "x-feedback": [
        "no-publish", "no-coauthored", "italiano", "numeri-misurati",
        "fonti-fresche", "no-llm-vibes", "task-tracker", "minimal-edits",
        "no-overengineering", "test-before-commit", "small-prs",
    ],
    "x-project": [
        "milestone", "decision", "blocker", "rollout", "experiment",
        "deprecation", "migration", "audit", "spike", "sla",
    ],
    "x-reference": [
        "repo", "doc", "issue", "rfc", "paper", "thread", "asset",
    ],
}

LOREM = [
    "regola di collaborazione che non vogliamo dimenticare a meta progetto.",
    "decisione architetturale presa dopo discussione, motivazione nel body.",
    "preferenza di stile: questo si fa, quest'altro no, sempre cosi.",
    "vincolo operativo: qualcosa che si rompe se non lo rispetti.",
    "convenzione di naming usata in tutto il codebase per coerenza.",
    "trade-off accettato consapevolmente, non risolverlo a meno di nuovi dati.",
    "anti-pattern individuato in passato, evitare di reintrodurlo per fretta.",
    "scelta di tooling: questo strumento copre il caso, alternative respinte.",
]


def make_id(kind: str, topic: str, n: int) -> str:
    short = kind.split("-", 1)[1]
    return f"{short}-{topic}-{n:03d}"


def pick_kind(rng: random.Random) -> str:
    r = rng.random()
    acc = 0.0
    for k, p in KINDS:
        acc += p
        if r <= acc:
            return k
    return KINDS[-1][0]


def gen_block(rng: random.Random, idx: int, existing_ids: list[str]) -> str:
    kind = pick_kind(rng)
    topic = rng.choice(TOPICS[kind])
    bid = make_id(kind, topic, idx)
    desc = f"{topic.replace('-', ' ')} ({idx})"
    body_lines = rng.randint(2, 5)
    body = "\n".join(rng.choice(LOREM) for _ in range(body_lines))

    refs_attr = ""
    if existing_ids and rng.random() < 0.30:
        n_refs = rng.choice([1, 1, 1, 2])
        targets = rng.sample(existing_ids, min(n_refs, len(existing_ids)))
        refs_attr = ' refs="' + " ".join(f"#{t}" for t in targets) + '"'

    head = f'@{kind} desc="{desc}"{refs_attr} [#{bid}]'
    return f"{head}\n~~~\n{body}\n~~~", bid


HEADER = """@meta format=agd generated=synthetic owner=bench project=agd-memory-bench version=1 [#meta]

@h1 Synthetic memory for benchmark [#root]

@p Generated by benchmarks/scripts/generate.py. TOC: `agd ids <file>`. Single block: `agd get <file> <id>`. Filter by kind: `agd ids <file> --kind x-user|x-feedback|x-project|x-reference`. Body in fence.

@! ============================================================
"""


def generate(n_blocks: int, seed: int) -> str:
    rng = random.Random(seed)
    parts = [HEADER]
    ids: list[str] = []
    for i in range(1, n_blocks + 1):
        block, bid = gen_block(rng, i, ids)
        ids.append(bid)
        parts.append(block)
        parts.append("")
    return "\n".join(parts) + "\n"


def generate_with_anchor(n_blocks: int, n_inbound: int, seed: int) -> str:
    """Generate a corpus where one anchor block has `n_inbound` backlinks.

    Used by S6 to measure backlink explosion. The anchor sits at index 1
    so that backlinkers (later blocks) can point at it via refs=.
    """
    rng = random.Random(seed)
    parts = [HEADER]
    anchor_id = "project-anchor-001"
    parts.append(
        f'@x-project desc="popular anchor block" [#{anchor_id}]\n'
        f"~~~\nBlocco di riferimento per il benchmark di backlink explosion.\n~~~"
    )
    parts.append("")
    ids = [anchor_id]

    for i in range(2, n_blocks + 1):
        kind = pick_kind(rng)
        topic = rng.choice(TOPICS[kind])
        bid = make_id(kind, topic, i)
        desc = f"{topic.replace('-', ' ')} ({i})"
        body_lines = rng.randint(2, 5)
        body = "\n".join(rng.choice(LOREM) for _ in range(body_lines))

        # First n_inbound non-anchor blocks point at anchor.
        if (i - 1) <= n_inbound:
            refs_attr = f' refs="#{anchor_id}"'
        elif ids and rng.random() < 0.30:
            n_refs = rng.choice([1, 1, 2])
            targets = rng.sample(ids, min(n_refs, len(ids)))
            refs_attr = ' refs="' + " ".join(f"#{t}" for t in targets) + '"'
        else:
            refs_attr = ""

        head = f'@{kind} desc="{desc}"{refs_attr} [#{bid}]'
        parts.append(f"{head}\n~~~\n{body}\n~~~")
        parts.append("")
        ids.append(bid)
    return "\n".join(parts) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True, help="output .agd file")
    ap.add_argument("--blocks", type=int, required=True)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument(
        "--anchor-inbound",
        type=int,
        default=0,
        help="If >0, generate a corpus with one popular anchor block "
        "having this many inbound refs= (used by S6).",
    )
    args = ap.parse_args()

    if args.anchor_inbound > 0:
        text = generate_with_anchor(args.blocks, args.anchor_inbound, args.seed)
    else:
        text = generate(args.blocks, args.seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    note = f"{args.blocks} blocks"
    if args.anchor_inbound > 0:
        note += f", anchor with {args.anchor_inbound} inbound"
    print(f"wrote {args.out} ({len(text)} bytes, {note})")


if __name__ == "__main__":
    main()
